// Helper function to get coordinates for a given district & city combo
export function getCityCoordinates(districtName: string, cityName: string): { latitude: number; longitude: number } {
  // If city is explicitly mapped in dictionary
  if (CITY_COORDINATES[cityName]) {
    return {
      latitude: CITY_COORDINATES[cityName].lat,
      longitude: CITY_COORDINATES[cityName].lng
    };
  }

  // Fallback to district center with spread offset based on city index
  const distObj = SRI_LANKA_DISTRICTS.find(d => d.name === districtName) || SRI_LANKA_DISTRICTS[0];
  const cityIndex = Math.max(0, distObj.cities.indexOf(cityName));
  
  const totalCities = Math.max(1, distObj.cities.length);
  const angle = (cityIndex / totalCities) * 2 * Math.PI;
  const radius = 0.035 + (cityIndex * 0.004);

  return {
    latitude: parseFloat((distObj.lat + Math.sin(angle) * radius).toFixed(4)),
    longitude: parseFloat((distObj.lng + Math.cos(angle) * radius).toFixed(4))
  };
}
